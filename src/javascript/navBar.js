/**
 * navBar — равная высота пилюль нижнего бара на телефоне.
 *
 * Внизу экрана стоят две пилюли: меню студии слева и счётчик кейсов справа.
 * Высота у каждой своя, по содержимому, и когда они расходятся на пару
 * пикселей, это читается не как два разных блока, а как один кривой: на
 * прокрученной главной меню 84, счётчик 76.
 *
 * Поэтому близкие высоты подтягиваются к большей, а заметно разные остаются
 * как есть — на странице всех кейсов счётчик разворачивается в перечень и
 * выше меню на 42, тянуть меню за ним незачем. Граница — шаг шкалы отступов:
 * ниже 16 разница уже не выглядит намеренной.
 *
 * Высоты меряются сами, а не берутся из CSS: у меню их три (полное,
 * компактное, с раскрытым списком услуг), у счётчика две, и расписать все
 * пары правилами — значит завести ещё один источник правды о высоте.
 */

const LIMIT = 16;

const menu = document.querySelector(".O_Menu");
const widget = document.querySelector(".M_CasesWidget");
/* Бар существует только на телефоне: выше обе пилюли стоят в колонке слева
   друг над другом и равнять там нечего. */
const bar = window.matchMedia("(max-width: 480px)");

if (menu && widget && "ResizeObserver" in window) {
  const pills = [menu, widget];

  const equalize = () => {
    /* Сначала снимаем своё: натуральную высоту иначе не замерить, да и
       анимация меню не должна упираться в вчерашнее значение. */
    pills.forEach((pill) => (pill.style.minHeight = ""));

    if (!bar.matches) return;

    /* Пока menuScroll ведёт морфинг меню, высота у коробки инлайновая и
       промежуточная — мерить нечего. Пересчитаем на последнем кадре: gsap
       снимет инлайн, размер изменится ещё раз, и наблюдатель нас разбудит. */
    if (menu.style.height) return;

    const heights = pills.map((pill) => pill.offsetHeight);
    const tallest = Math.max(...heights);

    if (tallest - Math.min(...heights) >= LIMIT) return;

    /* Значение то же, что и было, — не трогаем: лишняя запись разбудила бы
       наблюдателя на пустом месте. */
    pills.forEach((pill, i) => {
      if (heights[i] !== tallest) pill.style.minHeight = `${tallest}px`;
    });
  };

  /* Пересчёт откладывается на следующий кадр: внутри самого обработчика
     наблюдателя менять размеры нельзя — браузер уходит на второй круг и
     роняет в консоль «ResizeObserver loop completed with undelivered
     notifications». Из кадра же правка видна наблюдателю как обычное
     изменение, и на следующем круге она совпадает с уже посчитанной. */
  let frame = 0;

  const schedule = () => {
    if (frame) return;

    frame = requestAnimationFrame(() => {
      frame = 0;
      equalize();
    });
  };

  /* Высота пилюль меняется не по событию, а по содержимому: у меню — когда
     гаснет вступление или раскрывается список услуг, у счётчика — когда
     внизу появляется строка точек. Наблюдатель ловит все эти случаи разом,
     включая поворот экрана. */
  const observer = new ResizeObserver(schedule);

  /* Следим и за содержимым пилюли, а не только за ней самой. Пока она
     держит наш min-height, её собственная коробка при изменениях внутри не
     шелохнётся, и наблюдатель промолчит: так счётчик оставался высоким
     после того, как строка точек схлопнулась, вместо того чтобы снова
     сесть по содержимому. */
  pills.forEach((pill) => {
    observer.observe(pill);
    [...pill.children].forEach((block) => observer.observe(block));
  });
  bar.addEventListener("change", schedule);
  schedule();
}
